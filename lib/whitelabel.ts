export const GUEST_FALLBACK_KEY = 'plain';

/**
 * **이 채널이 이 차를 팔 수 있나 — 공급사 전용 채널의 «울타리».**
 *
 * 사장님 2026-09-08 「**이안카 차만 모아서 주는 거**」 — 그 약속을 지키는 자리다.
 *
 * ⚠⚠ **2026-09-10 코덱스 검토에서 이 울타리가 «없다»는 것이 운영에서 재현됐다.**
 * ```
 *   /api/catalog/feed?p=RP023&wl=eancar  → 오토플러스 71대가 이안카 채널로 나왔다
 *   /q/RP023_05수4035?wl=eancar          → 200 · 이안카 간판 아래 남의 차 상세가 열렸다
 * ```
 *   ㉠ 목록은 **손님이 준 `?p=`** 를 그대로 믿었다 ㉡ 상세는 채널을 아예 안 봤다.
 *   즉 주소 한 줄로 그 회사 홈페이지에 **남의 재고**를 세울 수 있었다.
 *
 * ★그래서 판정은 **여기 한 곳**이다 — 문이 셋(목록 API·상세 API·상세 페이지)인데
 *   각자 판정하면 한 곳만 고쳐지고 나머지로 새어 나간다. 실제로 그렇게 새고 있었다.
 * ★`providerCode` 가 **없는 채널은 울타리가 없다** — 영업채널은 «우리 재고 전체»를 제 이름으로
 *   파는 것이라 그게 정상이다(위 `providerCode` 머리말). 그때는 늘 `true` 다.
 * ⚠ 차의 공급사는 두 칸에 온다(`provider_company_code` · `partner_code`) — 목록 거르개와
 *   **같은 두 칸**을 본다. 한 칸만 보면 목록엔 있는데 상세가 안 열리는 차가 생긴다.
 */
export function channelSellsProduct(wl: Whitelabel, product: unknown): boolean {
  const only = String(wl.providerCode || '').trim();
  if (!only) return true;
  const p = (product || {}) as Record<string, unknown>;
  return String(p.provider_company_code ?? '').trim() === only
    || String(p.partner_code ?? '').trim() === only;
}

/**
 * **손님 공개 문이 «어느 공급사로» 걸러야 하나** — 손님이 준 값을 믿지 않는다.
 *
 * ⚠ `?p=` 는 손님이 주소창에서 고칠 수 있는 값이다. 채널이 제 코드를 가졌으면 **그것이 이긴다.**
 * ★코드가 없는 채널에서만 `?p=` 를 쓴다 — 그 채널은 이미 재고 전체를 파는 곳이라
 *   거기서 `?p=` 는 «울타리»가 아니라 그냥 «추림»이다(새는 것이 없다).
 */
export function guestProviderFence(wl: Whitelabel, askedProviderCode?: string | null): string {
  const only = String(wl.providerCode || '').trim();
  return only || String(askedProviderCode ?? '').trim();
}

/**
 * **손님 동 브랜드 판정** — 호스트 → `?wl=` → **임시 채널**.
 *
 * 사장님 2026-09-06 「프리패스 erp 점 컴에서 **원래 상세 페이지가 조회되거나 그러면 안 되는데**」.
 * 맞다. `www.freepasserp.com/q/<토큰>` 에서 `?wl=` 꼬리표만 떼면 **프리패스 「상품 안내」**가 떴고,
 * `/shop` 은 재고 전체를 프리패스 껍데기로 공개하고 있었다. 손님이 주소창에서 지울 수 있는 값이
 * 브랜드를 정하고 있었던 것이다(카톡 미리보기 봇은 애초에 안 붙은 주소를 긁는다).
 *
 * ★★**호스트가 여전히 정본이다.** 여기는 «못 찾았을 때만» 떨어지는 자리라, 채널 도메인을 붙이면
 *   그 순간 위에서 끝나고 이 줄은 안 탄다 — **코드를 다시 안 고쳐도 된다**(사장님 「나중에 별도
 *   도메인 붙일 수 있게」). 기본값은 채널이 둘이 된 날 정했다 — 위 `GUEST_FALLBACK_KEY` 머리말.
 * ⚠ 이미 카톡·문자로 나간 `freepasserp.com/q/...` 링크는 **안 죽는다** — 브랜드만 바뀐다.
 *   라우트를 닫는 쪽이 깨끗하지만, 손님이 지금 손에 들고 있는 링크가 대부분 이 도메인이다.
 */
export function resolveGuestWhitelabel(host?: string | null, wlKey?: string | null): Whitelabel {
  const wl = resolveWhitelabel(host, wlKey);
  /*
   * ★**«가게»면 그대로 쓴다 — 라벨이 없어도.**
   *   ⚠ 여기 `hasBrand` 였다. 그래서 라벨 없는 얼굴(`plain`)을 지목해도 「이름이 없다」는 이유로
   *     기본 채널(유니오토)로 떨어졌다 — 노브랜드로 보려던 화면에 남의 간판이 섰다.
   */
  if (hasShopFrame(wl)) return wl;
  return WHITELABELS.find((w) => w.key === GUEST_FALLBACK_KEY) || wl;
}

/**
 * **회사 «라벨»이 붙는가** — 이름·워드마크·마크를 세우는가.
 *
 * 사장님 2026-09-09 「**화이트라벨은 회사 라벨이 붙는 거**고, 프리패스erp.com 기본은
 * **라벨이 없는 거**지」.
 * ⚠ 이 함수는 「가게 껍데기를 그리는가」가 **아니다** — 그건 `hasShopFrame` 이다.
 *   라벨 없는 얼굴(`plain`)은 **껍데기는 쓰되 이름은 안 단다.**
 */
export function hasBrand(wl: Whitelabel): boolean {
  return !!wl.name || !!wl.wordmark.main;
}

/**
 * **가게 껍데기(머리띠·푸터·하단독)를 세우는가.**
 *
 * ★라벨이 붙는 업체(화이트라벨)든 **라벨 없는 기본 얼굴**(`plain`)이든 «가게»다 —
 *   손님이 매물을 보는 화면이므로 머리띠와 푸터가 있어야 한다
 *   (사장님 2026-09-09 「일단 비워봐 **상단바를 없앨 수는 없으니까**」).
 * ⚠ 업무동 기본값(`FREEPASS`)은 여기서도 false 다 — 거기는 콕핏이고, 이름도 껍데기도 없다.
 *   그래야 `freepasserp.com/` 이 로그인 현관으로 남는다(`homeIsShop` 머리말의 그 벽).
 */
export function hasShopFrame(wl: Whitelabel): boolean {
  return hasBrand(wl) || !!wl.plain;
}

/**
 * ★★★**진화 스위치 ② — `freepasserp.com` 의 «첫 화면»이 가게인가.**
 *
 * 사장님 2026-09-09 「우리 링크 있잖아 거기를 고도화해서 그게 **메인 프리패스erp.com 으로 진화**하자.
 * 그 준비를 명확하게 하자」.
 *
 * ```
 *  false (지금)  freepasserp.com/  →  /login          업무동 현관
 *  true  (진화)  freepasserp.com/  →  /shop(우리 간판)  손님이 상품부터 본다
 * ```
 *
 * ★채널 도메인(`uniautofreepass.com`·`freepassmobility.com`)은 **스위치와 무관하게 예전부터 가게**다.
 *   그래서 이 스위치는 「우리 도메인도 그렇게 할까」 하나만 정한다.
 * ★**로그인 길은 안 막힌다** — `/login` 은 이 판정을 타지 않는다. 가게 푸터의 「담당자 로그인」과
 *   주소 직접 입력 둘 다 그대로 산다(기계가 지킨다 — `npm run check:guest`).
 * ⚠ 켜기 전에 정해야 할 것 하나 = **이미 로그인한 사람이 `/` 로 오면 어디로 가나.**
 *   지금은 「가게」가 답이다(손님 화면은 누구에게나 열려 있다). 업무 화면으로 보내고 싶으면
 *   그건 «따로» 정할 일이라 이 스위치에 섞지 않는다.
 */
export const HOME_IS_SHOP = false;

/**
 * **이 호스트의 `/` 가 가게인가** — 미들웨어(다시쓰기)와 공개 판정이 «같은 답»을 봐야 한다.
 *
 * ⚠⚠ 전에는 두 곳이 **각자** `hasBrand(resolveWhitelabel(host))` 를 계산했다. 그래서 한쪽만
 *   고치면 **서버는 가게를 그리는데 클라이언트 게이트가 로그인으로 튕기는** 반쪽 상태가 된다
 *   (2026-09-04 에 실제로 그렇게 났다). 답을 한 곳에서 낸다.
 * ★루트 레이아웃은 이 함수를 **안 쓴다** — 거기는 「이 요청이 손님 화면인가」를 미들웨어가 붙인
 *   `x-fp-guest` 로 안다. 호스트로 판정하게 두면 스위치를 켠 순간 업무동 전 층에서 상단바가 사라진다.
 */
export function homeIsShop(host?: string | null): boolean {
  /* ★라벨이 붙은 업체든 «라벨 없는 얼굴»(plain)이든 가게다 — 그래서 `hasShopFrame` 이다. */
  if (hasShopFrame(resolveWhitelabel(host))) return true;
  return HOME_IS_SHOP;
}

/**
 * `.fp-wl` 스코프에 얹을 토큰 뒤집기.
 * ★원자에 색을 칠하지 않는다 — `--brand`/`--text-link` 만 바꾸면 `C.brand`·`C.accent` 를 쓰는
 *   원자가 전부 따라온다(globals.css `.fp-topbar .fp-onbar` 와 같은 짜임).
 */
export function whitelabelVars(wl: Whitelabel): Record<string, string> {
  /*
   * ★★**바탕은 «라벨과 무관하게» 흰색이다.**
   *   손님 화면 바탕은 흰색이 규격인데(업무동 기본값 `--bg-page:#eaedf2` 는 하루 종일 보는
   *   콕핏용이다), 그 값이 여태 «브랜드색이 있을 때만» 걸렸다. 그대로 두면 **라벨 없는 얼굴**은
   *   가게인데도 회색 판때기로 뜬다 — 색은 없어도 바탕은 흰색이어야 한다
   *   (사장님 2026-09-04 「전체적으로 배경도 회색이고」 — 그때 고친 그 값이다).
   */
  const ground: Record<string, string> = hasShopFrame(wl) ? { '--bg-page': '#ffffff' } : {};
  if (!wl.brandColor) return ground;
  return {
    '--brand': wl.brandColor,
    '--brand-h': wl.brandColor,
    '--text-link': wl.brandColor,
    /**
     * ★손님 화면 바탕은 **흰색**이다. 업무동 기본값(`--bg-page: #eaedf2`)은 하루 종일 보는
     * 콕핏이라 눈이 덜 부시게 회색으로 깔아 둔 것인데, 손님 카탈로그에 그대로 나오면
     * 「회색 판때기」로 보인다(사장님 2026-09-04 「전체적으로 배경도 회색이고」).
     * 중고차·렌터카 마켓은 전부 흰 바탕이다.
     */
    '--bg-page': '#ffffff',
    // 면(面)으로 깔 옅은 틴트 — 브랜드색에서 «자동으로» 뽑는다.
    // 채널마다 손으로 틴트 hex 를 적게 하면 그 값이 언젠가 브랜드색과 어긋난다.
    '--brand-bg': `color-mix(in srgb, ${wl.brandColor} 12%, white)`,
    '--brand-soft': `color-mix(in srgb, ${wl.brandColor} 6%, white)`,
  };
}
