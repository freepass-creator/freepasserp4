/**
 * 옛 기억 키 — **이제 쓰지 않는다. 만나면 지우기만 한다.**
 * ★남겨 두면 예전에 박힌 값이 브라우저마다 계속 굴러다닌다. 읽지 않으니 해는 없지만,
 *   다음 사람이 개발자도구에서 이 키를 보고 「아직 쓰는 값」으로 오해한다.
 * ★이 한 줄이 이미 박혀 있는 브라우저의 「강호준」도 다음 방문에 지워 준다.
 */
const LEGACY_ATTR_KEY = 'fp4_attr';

export function resolveAttr(params: URLSearchParams): string {
  if (typeof window === 'undefined') return '';
  try { localStorage.removeItem(LEGACY_ATTR_KEY); } catch { /* 못 지워도 읽지 않으니 상관없다 */ }

  const fromUrl = String(params.get('a') || '').trim();
  if (fromUrl) return fromUrl;

  // 로그인해서 «직접» 열어 본 영업자 — 이 화면은 그 사람 것이다.
  try { return String(getSession()?.user_code || '').trim(); } catch { return ''; }
}
