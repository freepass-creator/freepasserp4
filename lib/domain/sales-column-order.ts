export const SALES_COLUMN_ORDER: readonly string[] = [
  ...SALES_HEAD_FIXED,
  ...SALES_SECTIONS.flatMap((s) => s.columns),
];

/** 어느 칸이 어느 묶음에 드는가 — 화면·문서에서 구역을 말할 때. */
export const sectionOf = (column: string): string =>
  SALES_HEAD_FIXED.includes(column)
    ? '고정 앞자리'
    : SALES_SECTIONS.find((s) => s.columns.includes(column))?.title || '';
