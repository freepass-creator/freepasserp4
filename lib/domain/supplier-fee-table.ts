/**
 * 원장의 율 칸 값 하나를 읽는다. **1 보다 크면 율이 아니라 금액이다.**
 *   0.0475 → 정률 4.75% · 1000000 → 정액 1,000,000(기준 「고정」)
 *   ⚠ 0.5(=50%)와 50(=50원?)을 사람이 헷갈려 넣은 자리가 실제로 있었다(리더스렌트카).
 *     그래서 1 을 경계로 삼되, 1~100 사이는 «모름»으로 돌려 사람이 보게 한다.
 */
export function readFeeCell(raw: unknown): { kind: 'rate' | 'amount' | 'unknown'; value: number } {
  const n = Number(String(raw ?? '').replace(/[^0-9.-]/g, ''));
  if (!Number.isFinite(n) || n === 0) return { kind: 'unknown', value: 0 };
  if (n > 0 && n < 1) return { kind: 'rate', value: n };
  if (n >= 1000) return { kind: 'amount', value: n };
  return { kind: 'unknown', value: n };
}

export const feeRateText = (n: number) => `${(n * 100).toFixed(2).replace(/\.?0+$/, '')}%`;
export const feeAmountText = (n: number) => n.toLocaleString('ko-KR');
