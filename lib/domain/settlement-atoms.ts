const flat = (v: string) => v.replace(/[\s()（）]/g, '');

/** 이름으로 원자를 찾는다. */
export const atomByName = (name: string): Atom | undefined =>
  SETTLEMENT_ATOMS.find((a) => flat(a.name) === flat(name));

/**
 * **원본 머리글 → 원자.** 자리가 아니라 «이름»으로 붙인다.
 * ★원본 37탭 중 28개 열의 자리가 흔들린다(실측 2026-08-26) — 자리로 옮기면 한 칸 밀린 값이 돈이 된다.
 */
export function bySource(header: string): Atom | undefined {
  const h = flat(header);
  if (!h) return undefined;
  return SETTLEMENT_ATOMS.find((a) => flat(a.name) === h || (a.src || []).some((s) => flat(s) === h));
}

/** 이 줄이 실적·정산으로 돌 수 있나. **못 돌면 무엇이 없어서인지** 같이 돌려준다. */
export function missingRequired(row: Record<string, unknown>): Atom[] {
  return SETTLEMENT_ATOMS.filter((a) => a.need === '필수' && a.fill === '사람')
    .filter((a) => String(row[a.name] ?? '').trim() === '');
}
