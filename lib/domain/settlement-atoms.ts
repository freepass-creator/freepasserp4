/**
 * **실적·정산 원자 사전 — 무엇을 한 칸으로 볼 것인가.**
 *
 * ★사장님 2026-08-26
 *   「우리가 erp에서 틀을 먼저 잡고 기존 원본 정산시트에서 값들을 원자화해서 갖고오면 되거든」
 *   「차량번호 영업자 고객 상품분류 이런거는 있을거고」
 *
 * 그래서 순서가 이렇다 — **틀이 먼저고, 값이 나중이다.**
 *   원본을 보고 틀을 만들면 원본의 흐트러짐이 그대로 틀이 된다.
 *   틀을 먼저 세우고 원본을 부으면, 안 들어가는 값이 «드러난다». 그게 우리가 알아야 할 것이다.
 *
 * ★★**한 뜻에 이름 하나.** 원본은 같은 것을 여러 이름으로 부른다(실측 2026-08-26, 원본 50열) —
 * ```
 * 판매 수수료 · 판매 수수료 (수식X) · 계약완료건 수수료          → 판매수수료 하나
 * 출고수수료 · 출고 수수료 (수식X) · 에이전시 지급액 · 지급액     → 출고수수료 / 지급액 둘
 * 업체명 · 공급사                                            → 공급사 하나
 * 에이전시                                                  → 영업채널  (사람이 아니라 «회사»다)
 * 영업자                                                    → 영업담당자(회사가 아니라 «사람»이다)
 * ```
 *   ⚠ 이름이 둘이면 어느 쪽을 셌는지 아무도 모른다. 그래서 사전이 정본이고 별칭은 «들어오는 문»일 뿐이다.
 *
 * ★★**자리로 읽지 않는다.** 원본 37탭 중 28개 열의 «자리가 흔들린다»(실측) —
 *   「추가 인센티브」는 25·26·27·35·36·39·40번째에 다 나온다. 자리로 옮기면 한 칸 밀린 값이 돈이 된다.
 *   그래서 `bySource()` 로 **이름을 보고** 붙인다.
 *
 * ★★**원본에는 체크가 없다.** 계약서·인도완료·계약취소·환수가 「상태 표기」 글자 하나에 뭉쳐 있었다.
 *   푸는 것은 기계가 못 한다 — 사람이 정하거나 인도일 같은 «사실»에서 끌어낸다.
 */

/** 칸에 무엇이 들어가나. 서식·검증·합계가 여기서 갈린다. */
export type AtomKind = '글' | '돈' | '날짜' | '수' | '체크' | '택1';

/** 무엇에 쓰이는 칸인가. **갈래가 다르면 섞어 놓지 않는다.** */
export type AtomGroup =
  | '뼈대'   // 누구의 무엇인가 — 이게 없으면 줄이 성립하지 않는다
  | '조건'   // 계약 조건 — 수수료의 «기준값»이 여기 있다
  | '진행'   // 접수 → 계약서 → 인도 → 취소·환수. 실적의 관문
  | '정산'   // 돈. 받을 것(공급사)과 줄 것(영업채널) 두 갈래
  | '파생'   // 기계가 낸다. 사람이 적으면 반드시 갈린다
  | '참고';  // 있으면 좋고 없어도 도는 것

export type Atom = {
  /** 코드 키 */
  id: string;
  /** **하나뿐인 이름.** 원장 머리글·ERP 라벨이 이것과 같아야 한다. */
  name: string;
  group: AtomGroup;
  kind: AtomKind;
  /** 사람이 적나 기계가 채우나. ⚠ 기계 칸을 사람이 고치면 다음 실행에 덮인다. */
  fill: '사람' | '기계';
  /** 실적·정산이 돌기 위해 반드시 있어야 하나. */
  need: '필수' | '권장' | '있으면';
  /** **없으면 무엇이 안 되나.** 이 한 줄이 그 칸의 존재 이유다. */
  why: string;
  /** 원본 정산시트에서 이 원자를 가리키던 이름들. 들어오는 문일 뿐, 정본이 아니다. */
  src?: string[];
  /** 택1이면 선택지. 사람이 매번 새 말을 지어내면 집계가 안 된다. */
  opts?: string[];
};

