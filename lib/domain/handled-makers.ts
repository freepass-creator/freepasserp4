/**
 * 우리가 **취급하는 브랜드** — 차종 매칭의 후보를 여기로 좁힌다.
 *
 * 왜 필요한가: 차종마스터는 74개 브랜드를 담은 «사전»이라 국내 렌터카에서 볼 일 없는 차까지 들어 있다.
 * 그 사전을 그대로 후보로 쓰면 짧은 이름이 엉뚱한 브랜드에 걸린다 — 실측(2026-08-08):
 *   · 「BMW 120i 어드밴티지」 → **애스턴마틴 밴티지** (‘어드밴티지’ 안의 ‘밴티지’에 걸림)
 *   · 「E200 아방가르드」     → **크라이슬러 200**
 *   · 「BMW 220i」           → **인피니티 I30**
 * 손님 화면에 다른 차가 뜨는 사고다. 취급하지 않는 브랜드를 후보에서 빼면 이 부류가 통째로 사라진다.
 *
 * ★안전 계약
 *   · 이건 «금지»가 아니라 «우선»이다. 취급 목록에서 아무것도 못 찾으면 전체 마스터로 되돌아간다.
 *   · 공급사가 제조사를 명시하면 그 값이 이긴다 — 취급 목록에 없어도 그대로 쓴다.
 *     (실제로 들여온 차를 우리가 못 다룬다고 우길 수는 없다)
 *
 * 목록 근거: 재고·계약에 실제로 있던 브랜드 + 국내 렌터카/장기렌트 시장에서 실제로 유통되는 브랜드.
 * 새 브랜드를 취급하게 되면 여기 한 줄 추가하면 된다.
 */

const HANDLED = [
  // 국산
  '현대', '기아', '제네시스', '쉐보레', '르노', '르노코리아', '르노삼성',
  'KGM', 'KG모빌리티', '쌍용', '대우', '한국지엠', '삼성',
  // 수입 — 국내 장기렌트에서 실제로 도는 브랜드
  //
  // 실적 0 이면서 마스터 차종만 많은 브랜드는 뺐다(2026-08-08 결정).
  //   도요타 86 · 렉서스 68 · 푸조 50 · 혼다 41 · 포드 40 · 재규어 25 · 랜드로버 21 · 링컨 20
  //   = 차종 351개가 후보에서 빠진다. 재고·판매가 모두 0 이라 잃는 건 없고 오탐만 준다.
  // 포르쉐·BYD·폴스타는 실적은 아직 0 이지만 장기렌트로 실제로 들어올 수 있어 남긴다.
  '벤츠', '메르세데스', 'BMW', '아우디', '폭스바겐', '볼보', '미니', '테슬라',
  '지프', '포르쉐', '캐딜락', '폴스타', 'BYD',
] as const;

const norm = (value: unknown) => String(value ?? '').trim().toLowerCase().replace(/[\s_\-./]/g, '');
const HANDLED_SET = new Set(HANDLED.map(norm));

/** 이 브랜드를 취급하는가. 표기 흔들림(르노삼성/르노코리아, 메르세데스/벤츠)은 흡수한다. */
export function isHandledMaker(maker: unknown): boolean {
  const value = norm(maker);
  if (!value) return false;
  if (HANDLED_SET.has(value)) return true;
  // 「메르세데스-벤츠」·「르노코리아자동차」처럼 붙여 쓴 표기.
  for (const handled of HANDLED_SET) {
    if (handled.length >= 3 && (value.includes(handled) || handled.includes(value))) return true;
  }
  return false;
}
