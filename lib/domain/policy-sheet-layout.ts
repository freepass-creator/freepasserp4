/** 열쇠 두 칸 — 맨 앞에 선다. */
export const POLICY_KEY_COLUMNS = ['정책코드', '정책명'] as const;

/** 시트 머리행 전체. */
export const policySheetHeader = () => [...POLICY_KEY_COLUMNS, ...POLICY_SHEET_FIELDS.map((f) => f.name)];

/** 블록이 어디서 어디까지인가 — 머리 색을 칠하는 데 쓴다. */
export function policyBlocks(): { use: PolicyUse; from: number; to: number }[] {
  const out: { use: PolicyUse; from: number; to: number }[] = [];
  POLICY_SHEET_FIELDS.forEach((f, i) => {
    const at = i + POLICY_KEY_COLUMNS.length;
    const last = out[out.length - 1];
    if (last && last.use === f.use) last.to = at + 1;
    else out.push({ use: f.use, from: at, to: at + 1 });
  });
  return out;
}

