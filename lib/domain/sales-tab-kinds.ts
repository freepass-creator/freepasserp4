/**
 * **판매 탭 «갈래» — 한 곳에서 정한다. 시트마다 «이름»만 다르다.**
 *
 * ★★★사장님 2026-09-17
 *   「f01은 손오공 오토플러스 픽업만 분리하고 상품리스트에 다 들어가는거고」
 *   「f86은 손오공 오토플러스 픽업은 동일하게 유지하고 그냥 전체 렌트사 풀어서 탭으로 해주고
 *    종합에 넣어주면 될텐데 손오공 오플 픽업은 그냥 별개 유지하는거로 하고」
 *   「아예 고유로 손오공상품, 픽업구독, 오플구독 이거 3개는 탭이 아예 따로 고유로 다니자」
 *   「그거를 제외한 나머지는 모아놓은게 상품리스트고 하허호에서는 그게 종합이란 탭으로 오는거고
 *    하허호거에는 렌트사들 탭으로 다 존재하는거고」 · 「이러면 안헷갈린다」
 *   ★**「사실 상품리스트와 종합은 같은 거네 그러면」 · 「탭 이름만 달라지는거고」** ← 이 한마디가 정의다.
 *   ★「이렇게 플래시성으로 하지말고 앞으로 쭉 유지될수 있게끔」
 *
 * ⚠ **왜 헷갈렸나.** F01 은 「상품구분별 탭」, F86 은 「회사별 탭」이라는 **서로 다른 개념**으로 짜여
 *   있었다. 그래서 같은 것(고유 3갈래를 뺀 나머지)이 F01 에서는 「상품리스트」, F86 에서는 「종합」인데
 *   코드에는 그 둘이 «같다»는 말이 어디에도 없었다. 한쪽을 고치면 다른 쪽이 어긋난 이유가 이것이다.
 *
 * ⇒ 갈래는 넷이고, 시트는 그 갈래에 «이름표»만 붙인다:
 * ```
 *   갈래                       F01            F86
 *   ────────────────────────────────────────────────
  *   손오공상품(손오공 제 물건)    손오공상품      손오공상품
 *   픽업구독(손오공 픽업=T카)     픽업구독        픽업구독
 *   오플구독(오토플러스)          오플구독        오플구독
 * ```
 * ★F86 의 차이는 둘뿐이다 — ㉠ 겉이 «레트로»(맑은 고딕 9pt·옛 칸 색) ㉡ 위 넷 뒤에
 *   **공급사 탭이 쭉 나열된다**(이안카·아이카·빌린카…). 그 공급사 탭은 「상품리스트」를 회사별로
 *   쪼갠 것이라 갈래가 늘어난 게 아니다.
 *
 * ★지키는 법 = `npm run check:sales-tabs` — 갈래·이름표가 바뀌면 멈춘다.
 *   바꾸려면 사장님께 여쭙고 → 이 파일을 고치고 → 그 검사를 고친다(검사를 먼저 고치면 규격을 지운 것).
 */

/**
 * **갈래 넷 = 탭 이름 넷.** 이 순서가 시트 탭 차례다.
 * ★★사장님 2026-09-17 「아냐 탭을 같이 하자」·「탭 이름을 동일하게 맞추고 하허호 전용 시트에만
 *   나머지 공급사 탭을 쭉 나열해주면 되는거였어」·
 *   「상품리스트  손오공상품 픽업구독 오토플러스 ←여기까지는 동일, 대신 하허호는 레트로 시트로
 *    가는거지 그리고 공급사탭이 쭈욱 있고」
 *   ⇒ 시트별 «이름표»가 따로 없다. F01·F86 이 **같은 이름**을 쓴다 — 그래서 헷갈릴 자리가 없다.
 *   ⚠ 옛 이름은 발행에 쓰지 않는다(읽기 별칭만): F86 「종합」→「상품리스트」 ·
 *     F01 「오공구독」→「손오공상품」 · 「오플구독」→「오토플러스」.
 */
export const SALES_TAB_KINDS = ['상품리스트', '손오공상품', '픽업구독', '오토플러스'] as const;
export type SalesTabKind = (typeof SALES_TAB_KINDS)[number];

/** 고유로 «따로 다니는» 셋 — 「상품리스트」에서 빠지고 제 탭을 갖는다. */
export const SALES_TAB_OWN_KINDS: readonly SalesTabKind[] = ['손오공상품', '픽업구독', '오토플러스'];

/** 옛 탭 이름 → 지금 이름. 시트에 남은 옛 탭을 찾을 때만 쓴다(발행은 지금 이름으로만). */
export const SALES_TAB_LEGACY_NAMES: Record<string, SalesTabKind> = {
  종합: '상품리스트',
  오공구독: '손오공상품',
  손오공구독: '손오공상품',
  오플구독: '오토플러스',
};

/**
 * **원자 → 갈래.** 판정은 여기 한 곳이다.
 * ★손오공(RP012)은 픽업이면 「픽업구독」, 아니면 «전부» 「손오공상품」 —
 *   중고렌트·오공구독 구분 없이 가격 구조(12~60·인수형·보증금 규칙)가 같아서 한 탭에 싣는다
 *   (사장님 2026-09-16 「그냥 반납형 칸을 같이 써, F01에도 손오공 중고렌트는」).
 * ★픽업 판정은 `photo-projection.isPickupPhotoAtom` 한 곳을 쓴다 — 여기서 다시 정하지 않는다.
 */
export function salesTabKindOf(atom: { provider_company_code?: unknown }, isPickup: boolean): SalesTabKind {
  if (isPickup) return '픽업구독';
  const provider = String(atom.provider_company_code ?? '').trim();
  if (provider === 'RP012') return '손오공상품';
  if (provider === 'RP023') return '오토플러스';
  return '상품리스트';
}

/** 「상품리스트」에 들어가나 — 고유 셋은 제 탭에만 선다. */
export const inSalesMainList = (kind: SalesTabKind): boolean => kind === '상품리스트';
